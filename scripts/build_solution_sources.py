#!/usr/bin/env python3
"""Bundle canonical Python solutions for the static solution reader."""

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    sources = {
        str(path.relative_to(ROOT)): path.read_text(encoding="utf-8")
        for path in sorted(ROOT.glob("contests/**/solution.py"))
    }
    content = "// Generated by scripts/build_solution_sources.py. Do not edit.\n"
    content += "window.KATALCODE_SOURCES = " + json.dumps(sources, indent=2) + ";\n"
    target = ROOT / "dist" / "solution-sources.js"
    if args.check:
        if not target.exists() or target.read_text(encoding="utf-8") != content:
            raise SystemExit("Run python3 scripts/build_solution_sources.py to refresh solution code.")
        print("Reader source code matches canonical solutions")
    else:
        target.write_text(content, encoding="utf-8")
        print(f"Bundled {len(sources)} solutions")


if __name__ == "__main__":
    main()
